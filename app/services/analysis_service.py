logger = logging.getLogger(__name__)

_PUNCT = re.compile(r"[^\w\s]", re.UNICODE)
_LEADING_JUNK = re.compile(r"^(?:[\s:;,\-•*]|\[(?:high|medium|low)\])+", re.IGNORECASE)


def clean_item(text: str) -> str:
    """some models add stuff like ': [medium] ' in front, remove it"""
    return _LEADING_JUNK.sub("", text).strip()

STANDING_NOTES = [
    "Search volumes are intentionally not reported: no keyword-volume or social-search data source is connected.",
    "Services marked `website_content` with `evidence_verified: true` are backed by a quote found on the site; "
    "`inferred` services are AI recommendations.",
    "SEO audit values (`analysis.seo_improvements.audit`) are measured from the live HTML, not generated by AI.",
]


def _normalize_text(text: str) -> str:
    text = unicodedata.normalize("NFKC", text).lower()
    text = text.replace("’", "'").replace("‘", "'").replace("“", '"').replace("”", '"').replace("&", " and ")
    text = _PUNCT.sub(" ", text)
    return " ".join(text.split())


def evidence_in_corpus(evidence: str, normalized_corpus: str) -> bool:
    """exact match after normalising, or 85%+ of word pairs match"""
    ev = _normalize_text(evidence)
    if len(ev) < 4:
        return False
    if ev in normalized_corpus:
        return True
    words = ev.split()
    if len(words) < 3:
        return False
    bigrams = [f"{a} {b}" for a, b in zip(words, words[1:])]
    hits = sum(1 for bg in bigrams if bg in normalized_corpus)
    return hits / len(bigrams) >= 0.85


class AnalysisService:
    def __init__(
        self,
        settings: Settings,
        extractor: WebsiteExtractor,
        llm: AnalysisLLM,
        competitor_service: CompetitorService,
        cache: TTLCache[LinkAnalysisResponse],
    ) -> None:
        self.settings = settings
        self.extractor = extractor
        self.llm = llm
        self.competitors = competitor_service
        self.cache = cache

    async def analyze(self, raw_url: str, *, request_id: str, force_refresh: bool = False) -> LinkAnalysisResponse:
        # validate before the cache so blocked urls never get a cached answer
        validated = await validate_public_url(raw_url, self.settings.allowed_ports)
        cache_key = normalize_url(validated.url).rstrip("/").lower()

        result, cached = await self.cache.get_or_compute(
            cache_key, lambda: self._run(validated.url, request_id), refresh=force_refresh
        )
        if cached:
            meta = result.meta.model_copy(update={"cached": True, "request_id": request_id})
            return result.model_copy(update={"meta": meta})
        return result

    async def _run(self, url: str, request_id: str) -> LinkAnalysisResponse:
        t0 = time.perf_counter()
        site = await self.extractor.extract(url)
        t_extract = time.perf_counter()

        llm_result = await self.llm.analyze(SYSTEM_PROMPT, build_user_prompt(site.to_llm_context(), site.seo_audit))
        t_llm = time.perf_counter()

        analysis, warnings = await self._post_process(llm_result.analysis, site)
        t_done = time.perf_counter()

        brand = Brand(
            **llm_result.analysis.brand.model_dump(),
            website=site.final_url,
            social_profiles=site.social_profiles,
        )
        meta = Meta(
            request_id=request_id,
            analyzed_at=datetime.now(timezone.utc),
            cached=False,
            content_sufficiency=llm_result.analysis.content_sufficiency,
            pages_analyzed=[PageInfo(url=p.url, title=p.title, chars_used=len(p.text)) for p in site.pages],
            content_chars_sent=site.total_chars,
            llm=LLMUsage(
                provider=llm_result.provider,
                model=llm_result.model,
                input_tokens=llm_result.input_tokens,
                output_tokens=llm_result.output_tokens,
                cache_read_input_tokens=llm_result.cache_read_input_tokens,
                estimated_cost_usd=llm_result.estimated_cost_usd,
                latency_ms=llm_result.latency_ms,
                fallback_used=llm_result.fallback_used,
            ),
            timings=Timings(
                extraction_ms=int((t_extract - t0) * 1000),
                llm_ms=int((t_llm - t_extract) * 1000),
                verification_ms=int((t_done - t_llm) * 1000),
                total_ms=int((t_done - t0) * 1000),
            ),
            warnings=site.warnings + warnings,
            notes=STANDING_NOTES + llm_result.analysis.analysis_notes,
        )
        logger.info(
            "Analysed %s: pages=%d chars=%d model=%s cost=$%.5f total=%dms",
            site.final_url, len(site.pages), site.total_chars, llm_result.model,
            llm_result.estimated_cost_usd, meta.timings.total_ms,
        )
        return LinkAnalysisResponse(website=site.final_url, brand=brand, analysis=analysis, meta=meta)

    async def _post_process(self, llm: LLMAnalysis, site: ExtractedWebsite) -> tuple[Analysis, list[str]]:
        warnings: list[str] = []

        # services - check the quotes are really on the site
        corpus = _normalize_text(site.corpus)
        services: list[Service] = []
        for svc in llm.top_services[:5]:
            verified = bool(svc.evidence) and evidence_in_corpus(svc.evidence, corpus)
            data = svc.model_dump()
            if svc.source == "website_content" and not verified:
                # says it's from the site but we can't find the quote
                warnings.append(f"Evidence for service '{svc.name}' could not be matched to the page text.")
            services.append(Service(**data, evidence_verified=verified))
        if len(services) < 5:
            warnings.append(f"Only {len(services)} services could be identified from the website.")

        # queries
        queries = [SearchQuery(**q.model_dump()) for q in llm.target_search_queries[:5]]
        if len(queries) < 5:
            warnings.append(f"Only {len(queries)} search queries were generated.")
        missing = [p for p in ("Google", "Facebook", "Instagram", "LinkedIn", "X")
                   if not any(p in q.platforms or q.primary_platform == p for q in queries)]
        if missing:
            warnings.append("No search query targets: " + ", ".join(missing) + ".")

        # competitors
        cleaned = self.competitors.clean(llm.competitor_analysis.competitors, llm.brand.name, site.domain)
        competitors = await self.competitors.enrich(cleaned)
        if len(competitors) < 3:
            warnings.append("Fewer than 3 reliable competitors could be identified.")
        unreachable = [c.name for c in competitors if c.website_status == "unreachable"]
        if unreachable:
            warnings.append("Suggested website could not be reached for: " + ", ".join(unreachable) + ".")
        comp_data = llm.competitor_analysis.model_dump()
        comp_data["competitors"] = competitors
        # drop table cells for competitors we removed
        kept = {c.name.lower() for c in competitors}
        for row in comp_data["comparison_table"]:
            row["competitors"] = [v for v in row["competitors"] if v["competitor"].lower() in kept]
        if competitors and any(not row["competitors"] for row in comp_data["comparison_table"]):
            warnings.append("Comparison table is missing competitor values in some rows.")
        competitor_analysis = CompetitorAnalysis(**comp_data, disclaimer=COMPETITOR_DISCLAIMER)

        # seo
        audit = site.seo_audit
        seo_data = llm.seo_improvements.model_dump()
        seo_data["technical_recommendations"] = [
            t for t in (clean_item(x) for x in seo_data["technical_recommendations"]) if t
        ]
        seo = SEOImprovements(
            **seo_data,
            current_title=audit.title,
            current_meta_description=audit.meta_description,
            recommended_title_length=len(llm.seo_improvements.recommended_title),
            meta_description_length=len(llm.seo_improvements.meta_description),
            audit=audit,
        )

        return (
            Analysis(
                competitor_analysis=competitor_analysis,
                target_search_queries=queries,
                seo_improvements=seo,
                top_services=services,
                target_audience=llm.target_audience,
            ),
            warnings,
        )
